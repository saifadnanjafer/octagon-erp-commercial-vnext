import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { openMigrationDatabase, migrationStatus, runMigrations, schemaFingerprint } from '../vnext/server/db/migration-runner.mjs';
import { applyR0ScopeSeed } from '../vnext/server/db/seed-runner.mjs';

const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'octagon-vnext-r0-'));
const dbPath = path.join(tempDir, 'fresh.db');
const backupDir = path.join(tempDir, 'backups');
const baselineDb = openMigrationDatabase(dbPath);
const baselineFingerprint = schemaFingerprint(baselineDb);
baselineDb.close();
const dry = await runMigrations({ dbPath, dryRun: true, backupDir });
assert.equal(dry.dryRun, true);
assert.equal(fs.existsSync(backupDir), false, 'dry run must not create a backup');
const up = await runMigrations({ dbPath, direction: 'up', backupDir });
assert.equal(up.status.every((entry) => entry.status === 'applied'), true);
assert.ok(up.backupPath && fs.existsSync(up.backupPath), 'migration must create a pre-migration backup');
const db = openMigrationDatabase(dbPath);
assert.throws(() => db.prepare('INSERT INTO r0_company_owned_probe (id, payload) VALUES (?, ?)').run('invalid', 'probe'), /NOT NULL/);
const firstSeed = applyR0ScopeSeed(db);
const secondSeed = applyR0ScopeSeed(db);
assert.equal(firstSeed.applied, true);
assert.equal(secondSeed.applied, false);
assert.throws(() => db.prepare('INSERT INTO r0_company_owned_probe (id, company_id, payload) VALUES (?, ?, ?)').run('invalid-company', 'company-does-not-exist', 'probe'), /FOREIGN KEY/);
db.prepare('INSERT INTO r0_company_owned_probe (id, company_id, payload) VALUES (?, ?, ?)').run('valid', 'company-r0-demo', 'probe');
assert.equal(db.prepare("SELECT company_id_policy FROM scope_table_registry WHERE table_name = 'schema_migrations'").get().company_id_policy, 'absent');
assert.equal(db.prepare("SELECT company_id_policy FROM scope_table_registry WHERE table_name = 'r0_tenant_root'").get().company_id_policy, 'self-root');
assert.equal(db.prepare("SELECT company_id_policy FROM scope_table_registry WHERE table_name = 'r0_company_owned_probe'").get().company_id_policy, 'required');
db.close();
const status = await migrationStatus(dbPath);
assert.equal(status.every((entry) => entry.status === 'applied'), true);
await runMigrations({ dbPath, direction: 'down', backupDir });
const afterDb = openMigrationDatabase(dbPath);
assert.equal(schemaFingerprint(afterDb), baselineFingerprint, 'up then down must restore the baseline schema fingerprint');
afterDb.close();
console.log(JSON.stringify({ status: 'pass', freshDatabase: 'built', status: 'clean', dryRun: 'pass', seedIdempotence: 'pass', companyIdNotNull: 'pass', schemaFingerprint: 'byte-identical baseline fingerprint', backupCreated: path.basename(up.backupPath) }, null, 2));
